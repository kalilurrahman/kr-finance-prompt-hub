/**
 * Download helpers for Meta-Prompt Engine outputs.
 * Supports: Markdown (.md), HTML (.html), PDF (print dialog).
 * All downloads include attribution footer: FinPrompt URL + Kalilur Rahman.
 */

// ─────────────────────────────────────────────
// Attribution Footer Content
// ─────────────────────────────────────────────

const FINPROMPT_URL = "https://kr-finance-prompt-hub.lovable.app/library";
const KALILUR_URL = "https://kalilurrahman.lovable.app";
const ENGINE_URL = "https://kr-finance-prompt-hub.lovable.app/engine";

function timestamp(): string {
  return new Date().toLocaleString("en-IN", { timeZone: "Asia/Kolkata" });
}

function footerMD(): string {
  return [
    "",
    "---",
    "",
    `📚 **Source:** [FinPrompt Library](${FINPROMPT_URL}) — Curated finance prompts for AI platforms`,
    `✍️ **Curated by** [Kalilur Rahman](${KALILUR_URL})`,
    `🤖 **Generated by** [Meta-Prompt Engine v1.0](${ENGINE_URL})`,
    `🕐 **Generated:** ${timestamp()}`,
    "",
  ].join("\n");
}

function footerHTML(): string {
  return `
  <footer>
    <hr style="margin: 32px 0 18px; border: none; border-top: 1px solid #ddd;">
    <p>📚 <strong>Source:</strong> <a href="${FINPROMPT_URL}">FinPrompt Library</a> — curated finance prompts for AI platforms</p>
    <p>✍️ <strong>Curated by</strong> <a href="${KALILUR_URL}">Kalilur Rahman</a></p>
    <p>🤖 <strong>Generated by</strong> <a href="${ENGINE_URL}">Meta-Prompt Engine v1.0</a></p>
    <p class="meta">🕐 Generated: ${timestamp()}</p>
  </footer>`;
}

// ─────────────────────────────────────────────
// Shared Utilities
// ─────────────────────────────────────────────

function triggerDownload(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1500);
}

function safeFilename(title: string): string {
  return title
    .replace(/[^a-z0-9\s]/gi, "")
    .replace(/\s+/g, "-")
    .toLowerCase()
    .slice(0, 50)
    .replace(/-+$/, "");
}

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

// ─────────────────────────────────────────────
// Markdown Download
// ─────────────────────────────────────────────

export function downloadMarkdown(content: string, title: string): void {
  const md = `# ${title}\n\n${content}\n${footerMD()}`;
  const blob = new Blob([md], { type: "text/markdown;charset=utf-8" });
  triggerDownload(blob, `${safeFilename(title) || "finprompt"}.md`);
}

