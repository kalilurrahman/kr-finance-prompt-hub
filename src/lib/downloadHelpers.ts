// ─────────────────────────────────────────────
// HTML Download
// ─────────────────────────────────────────────

export function downloadHTML(content: string, title: string): void {
  const html = buildHtmlDoc(content, title, false);
  const blob = new Blob([html], { type: "text/html;charset=utf-8" });
  triggerDownload(blob, `${safeFilename(title) || "finprompt"}.html`);
}

// ─────────────────────────────────────────────
// PDF (Print Dialog)
// ─────────────────────────────────────────────

export function downloadPDF(content: string, title: string): void {
  const html = buildHtmlDoc(content, title, true);

  const win = window.open("", "_blank", "width=900,height=700,scrollbars=yes");
  if (!win) {
    // Popup blocked — fallback to HTML download
    downloadHTML(content, title);
    return;
  }

  win.document.open();
  win.document.write(html);
  win.document.close();

  // Wait for fonts/layout to render before printing
  setTimeout(() => {
    win.focus();
    win.print();
    // Close print window after a delay
    setTimeout(() => {
      try { win.close(); } catch { /* ignore */ }
    }, 1200);
  }, 600);
}
